/*
# Make letter numbers editable

1. Changes
- `letters.letter_no` is now generated by default instead of always generated, so staff can set a specific letter number when needed.
- Adds a unique index on `letters.letter_no` so two letters cannot share a number.

2. Security
- No change to row level security or grants.

3. Notes
- New letters still receive the next number automatically when no number is entered.
*/

ALTER TABLE letters ALTER COLUMN letter_no SET GENERATED BY DEFAULT;

CREATE UNIQUE INDEX IF NOT EXISTS letters_letter_no_key ON letters (letter_no);
